"use client";

import { useState, useRef, useEffect } from "react";
import { Volume2, VolumeX, Download, Share2, Award, Zap, Briefcase, TrendingUp, Check, FileText } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { Tabs, TabsContent, TabsList, TabsTrigger } from "@/components/ui/tabs";
import { GenerateCareerReportOutput } from "@/ai/flows/generate-career-report";
import { readCareerReportAloud } from "@/ai/flows/read-career-report-aloud";
import { LearningRoadmap } from "./LearningRoadmap";
import { SkillGapAnalysis } from "./SkillGapAnalysis";
import { useToast } from "@/hooks/use-toast";

interface ReportDisplayProps {
  report: GenerateCareerReportOutput;
}

export function ReportDisplay({ report }: ReportDisplayProps) {
  const { toast } = useToast();
  const [isPlaying, setIsPlaying] = useState(false);
  const [isCopied, setIsCopied] = useState(false);
  const [isGeneratingAudio, setIsGeneratingAudio] = useState(false);
  const audioRef = useRef<HTMLAudioElement | null>(null);

  useEffect(() => {
    return () => {
      if (audioRef.current) {
        audioRef.current.pause();
        audioRef.current = null;
      }
    };
  }, []);

  const generateReportText = () => {
    let text = `AI CAREER GUIDANCE ANALYSIS REPORT\n`;
    text += `==================================\n\n`;
    text += `Match Score: ${report.careerMatchPercentage}%\n\n`;
    
    text += `SUGGESTED CAREER PATHS:\n`;
    report.careerSuggestions.forEach(c => text += `- ${c}\n`);
    text += `\n`;

    text += `RECOMMENDED JOB ROLES:\n`;
    report.topJobRoles.forEach(r => text += `- ${r}\n`);
    text += `\n`;

    text += `SKILL GAP ANALYSIS:\n`;
    text += `Current Skills: ${report.skillGapAnalysis.currentSkills.join(', ')}\n`;
    text += `Missing Skills: ${report.skillGapAnalysis.missingSkills.join(', ')}\n`;
    text += `Improvement Suggestions:\n`;
    report.skillGapAnalysis.improvementSuggestions.forEach(s => text += `- ${s}\n`);
    text += `\n`;

    text += `6-MONTH LEARNING ROADMAP:\n`;
    report.learningRoadmap.forEach(m => {
      text += `[${m.month}]\n`;
      m.activities.forEach(a => text += `  • ${a}\n`);
    });
    text += `\n`;

    text += `RESUME OPTIMIZATION TIPS:\n`;
    report.resumeTips.forEach(t => text += `- ${t}\n`);

    text += `\nGenerated by AI Career Guidance - Your Future, Architected.`;
    return text;
  };

  const handleSpeak = async () => {
    if (isPlaying && audioRef.current) {
      audioRef.current.pause();
      setIsPlaying(false);
      return;
    }

    try {
      setIsGeneratingAudio(true);
      const textToRead = `Analysis complete. Your top career match is ${report.careerSuggestions[0]}. Your overall match percentage is ${report.careerMatchPercentage} percent. Your recommended job roles include ${report.topJobRoles.join(', ')}.`;
      const { media } = await readCareerReportAloud(textToRead);
      
      const newAudio = new Audio(media);
      audioRef.current = newAudio;
      
      setIsGeneratingAudio(false);
      setIsPlaying(true);
      
      const playPromise = newAudio.play();
      
      if (playPromise !== undefined) {
        playPromise.catch(error => {
          if (error.name !== "AbortError") {
            console.error("Playback error:", error);
            setIsPlaying(false);
          }
        });
      }

      newAudio.onended = () => {
        setIsPlaying(false);
        audioRef.current = null;
      };
    } catch (error) {
      toast({ variant: "destructive", title: "Audio playback failed" });
      setIsGeneratingAudio(false);
      setIsPlaying(false);
    }
  };

  const handleDownload = () => {
    const text = generateReportText();
    const blob = new Blob([text], { type: "text/plain;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = "AI_Career_Guidance_Report.txt";
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
    toast({ title: "Report downloaded", description: "Your career roadmap is saved as a professional document." });
  };

  const handleShare = async () => {
    const text = generateReportText();
    
    if (navigator.share) {
      try {
        await navigator.share({
          title: 'My AI Career Guidance Report',
          text: text,
        });
        toast({ title: "Shared successfully" });
      } catch (err) {
        if ((err as Error).name !== 'AbortError') {
          copyToClipboard(text);
        }
      }
    } else {
      copyToClipboard(text);
    }
  };

  const copyToClipboard = async (text: string) => {
    try {
      await navigator.clipboard.writeText(text);
      setIsCopied(true);
      toast({ title: "Copied to clipboard", description: "Report text is ready to be shared." });
      setTimeout(() => setIsCopied(false), 2000);
    } catch (err) {
      toast({ variant: "destructive", title: "Share failed", description: "Could not copy text to clipboard." });
    }
  };

  return (
    <div className="space-y-8">
      <div className="flex flex-col md:flex-row justify-between items-start md:items-center gap-4 bg-primary/5 p-6 rounded-3xl border border-primary/20 shadow-xl shadow-primary/5">
        <div>
          <h2 className="text-3xl font-headline font-bold mb-2">Analysis Result</h2>
          <div className="flex items-center gap-3">
            <Badge variant="outline" className="text-primary border-primary px-3 py-1 font-bold">
              Match Score: {report.careerMatchPercentage}%
            </Badge>
            <span className="text-muted-foreground text-xs font-medium uppercase tracking-widest">Architected Future</span>
          </div>
        </div>
        <div className="flex items-center gap-2">
          <Button 
            variant="outline" 
            size="icon" 
            className={`glass rounded-xl transition-all ${isGeneratingAudio ? 'animate-pulse' : ''}`} 
            onClick={handleSpeak} 
            disabled={isGeneratingAudio}
            title="Listen to summary"
          >
            {isPlaying ? <VolumeX className="text-primary w-5 h-5" /> : <Volume2 className="text-primary w-5 h-5" />}
          </Button>
          <Button variant="outline" size="icon" className="glass rounded-xl hover:bg-white/5" onClick={handleDownload} title="Download Document">
            <Download className="w-5 h-5 text-primary" />
          </Button>
          <Button className="bg-primary hover:bg-primary/90 text-white rounded-xl px-6 group" onClick={handleShare}>
            {isCopied ? <Check className="w-4 h-4 mr-2" /> : <Share2 className="w-4 h-4 mr-2 group-hover:rotate-12 transition-transform" />}
            {isCopied ? "Copied" : "Share Report"}
          </Button>
        </div>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-3 gap-8">
        <div className="lg:col-span-2 space-y-8">
          <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
            {report.careerSuggestions.map((career, i) => (
              <div key={i} className="glass p-6 rounded-3xl border-white/5 hover:border-primary/30 transition-all group cursor-default shadow-lg">
                <div className="flex items-center gap-4 mb-4">
                  <div className="p-3 bg-primary/10 rounded-2xl group-hover:scale-110 transition-transform duration-500">
                    <Briefcase className="w-6 h-6 text-primary" />
                  </div>
                  <h3 className="font-headline font-bold text-xl">{career}</h3>
                </div>
                <div className="text-sm text-muted-foreground leading-relaxed">
                  Highly aligned with your skills and professional aspirations. Recommended based on industry trends.
                </div>
              </div>
            ))}
          </div>

          <Tabs defaultValue="roadmap" className="w-full">
            <TabsList className="glass w-full justify-start p-1.5 h-auto mb-8 rounded-2xl border-white/5">
              <TabsTrigger value="roadmap" className="px-8 py-3 rounded-xl data-[state=active]:bg-primary data-[state=active]:text-white transition-all font-bold">
                Roadmap
              </TabsTrigger>
              <TabsTrigger value="certs" className="px-8 py-3 rounded-xl data-[state=active]:bg-primary data-[state=active]:text-white transition-all font-bold">
                Certifications
              </TabsTrigger>
              <TabsTrigger value="future" className="px-8 py-3 rounded-xl data-[state=active]:bg-primary data-[state=active]:text-white transition-all font-bold">
                Trends
              </TabsTrigger>
            </TabsList>
            
            <TabsContent value="roadmap" className="focus-visible:outline-none">
              <LearningRoadmap roadmap={report.learningRoadmap} />
            </TabsContent>
            
            <TabsContent value="certs" className="focus-visible:outline-none">
              <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
                {report.recommendedCertifications.map((cert, i) => (
                  <div key={i} className="glass p-5 rounded-2xl flex items-start gap-4 border-white/5 hover:border-secondary/30 transition-all group">
                    <div className="p-2 bg-secondary/10 rounded-xl group-hover:rotate-12 transition-transform">
                      <Award className="w-6 h-6 text-secondary" />
                    </div>
                    <div>
                      <div className="font-bold text-secondary text-lg mb-1">{cert}</div>
                      <div className="text-xs text-muted-foreground leading-relaxed">Boost your professional credibility with this high-demand industry certification.</div>
                    </div>
                  </div>
                ))}
              </div>
            </TabsContent>
            
            <TabsContent value="future" className="focus-visible:outline-none">
              <div className="space-y-4">
                {report.futureOpportunities.map((opp, i) => (
                  <div key={i} className="glass p-6 rounded-2xl flex items-center gap-6 border-white/5 group hover:border-primary/20 transition-all">
                    <div className="p-3 bg-primary/5 rounded-full group-hover:scale-110 transition-transform">
                      <TrendingUp className="w-6 h-6 text-primary/60" />
                    </div>
                    <p className="text-sm font-medium italic text-muted-foreground leading-relaxed">"{opp}"</p>
                  </div>
                ))}
              </div>
            </TabsContent>
          </Tabs>
        </div>

        <div className="space-y-8">
          <SkillGapAnalysis analysis={report.skillGapAnalysis} />

          <div className="glass p-6 rounded-3xl border-white/10 shadow-xl">
            <h4 className="font-headline font-bold text-xl mb-6 flex items-center gap-3">
              <Zap className="w-6 h-6 text-amber-500 fill-amber-500/20" />
              Resume Boost
            </h4>
            <ul className="space-y-4">
              {report.resumeTips.map((tip, i) => (
                <li key={i} className="flex gap-4 text-sm text-muted-foreground border-b border-white/5 pb-4 last:border-0 last:pb-0">
                  <div className="w-6 h-6 rounded-full bg-primary/10 flex items-center justify-center shrink-0 text-[10px] font-bold text-primary">
                    {i + 1}
                  </div>
                  <span className="leading-relaxed">{tip}</span>
                </li>
              ))}
            </ul>
          </div>
          
          <div className="glass p-6 rounded-3xl border-primary/20 bg-primary/5 relative overflow-hidden group">
            <div className="absolute top-0 right-0 p-4 opacity-10 group-hover:scale-150 transition-transform duration-1000">
              <FileText className="w-24 h-24 text-primary" />
            </div>
            <h4 className="font-headline font-bold text-lg mb-2 relative z-10">Professional Summary</h4>
            <p className="text-xs text-muted-foreground leading-relaxed relative z-10">
              Based on our AI analysis, you are in a strong position for {report.careerSuggestions[0]}. Focusing on {report.skillGapAnalysis.missingSkills[0]} will accelerate your transition.
            </p>
          </div>
        </div>
      </div>
    </div>
  );
}
